"""Reading-box repairs: the MECHANICAL finding classes of the readings QA sweep.

Source audit: `research/reports/qa_sweep/readings_quality.md` (all 286 boxes read in full). That report
carries 20 findings; this script repairs only the three that are mechanical and unambiguous:

  * A2 -- 33 tokens whose `r` is the WRONG READING FOR THE SURFACE IN CONTEXT. Every one of these has a
    kanji surface, so `tokenRuby` (prototype/app/lib/render-body.server.ts) emits <ruby> and the learner
    is shown the wrong furigana today.
  * A3 -- 29 numeral tokens read digit by digit with `0` mapped to れい (５００００ -> ごれいれいれいれい),
    destroying place value.
  * B6 -- pt-BR translations wrapped in quotation marks that exist nowhere in the Japanese.

DELIBERATELY OUT OF SCOPE (queued as separate content work, do NOT let them ride along here):
A1/A8/A9/A10 (translation re-authoring), A4 (run-on junctions), A5 (duplicate selection), A6/A7
(selection-time pairing and register), A11 (placeholder titles), B1 (`ro` vs `r` drift), B2 (romaji
converter drift), B3 (whitespace tokens read きごう), B4 (tokenisation artefacts), B5 (`ai_generated`),
B7 (`length_band`), B8 (ungrammatical source sentences), B9 (one word two ways).

STORAGE MODEL. Reading boxes live ONLY in `db/corpus.sqlite` (`reading` table: `tokens` is a JSON array
of {s,r,ro,pos}; `translation_pt` is a plain column). `corpus/readings/*.json` is REGENERATED by
export_readings.py and is never edited here. This script does not run any exporter.

MATCHING. Every edit names the token's exact current `s`, `r` and `ro`. If the row is neither the
expected broken value nor the repaired value, the edit is SKIPPED LOUDLY and nothing is written.
Re-running after a successful run reports 0 changes.

ROMAJI CONVENTION (derived from the corpus itself, not invented here):
  * a token-final っ takes the consonant of the FOLLOWING token's first mora -- いっ+て = `it`, いっ+ぽん
    = `ip`, じゅっ+ぷん = `jup`, にじゅっ+さい = `nijus`, じゅっ+かこく = `juk`. Verified over the 309
    っ-final tokens already in `reading.tokens` (t/t x301, p/p, s/s, k/k, no counter-examples).
  * づ -> `zu` (つづけ|tsuzuke, づらい|zurai, きづい|kizui).
  * `read:n3-estado-07-02` already ships `１０=じゅっ/jup` + `分=ぷん/pun`, which is the exact shape the
    A3 repairs below reproduce.

Usage: apply_readings_furigana_repairs.py [--check]
"""
