# --------------------------------------------------------------------------------------------------
# plumbing
# --------------------------------------------------------------------------------------------------
class Repairs:
    def __init__(self, check: bool) -> None:
        self.check = check
        self.con = sqlite3.connect(DB)
        self.con.execute("PRAGMA busy_timeout=60000")
        self.changed = 0
        self.noop = 0
        self.skipped: list[str] = []
        self._tok: dict[str, list[dict]] = {}      # slug -> parsed tokens
        self._tok_dirty: set[str] = set()
        self._section = ""

    # ---- reporting ----
    def section(self, title: str) -> None:
        self._section = title
        print(f"\n== {title}")

    def hit(self, label: str, why: str) -> None:
        self.changed += 1
        print(f"  + {label}\n      why: {why}")

    def skip(self, label: str, reason: str) -> None:
        self.skipped.append(f"[{self._section}] {label}: {reason}")
        print(f"  ! SKIP {label}: {reason}")

    # ---- reading.tokens ----
    def tokens(self, slug: str):
        """Parse once, cache, and only ever re-serialise with the format the column already uses.

        All 286 rows round-trip byte for byte through json.dumps(obj, ensure_ascii=False), so an
        unrelated whitespace reflow can never ride along with a reading repair.
        """
        if slug in self._tok:
            return self._tok[slug]
        row = self.con.execute("SELECT tokens FROM reading WHERE slug=?", (slug,)).fetchone()
        if row is None or row[0] is None:
            return None
        raw = row[0]
        obj = json.loads(raw)
        if json.dumps(obj, ensure_ascii=False) != raw:
            return None
        self._tok[slug] = obj
        return obj

    def tok_save_all(self) -> None:
        for slug in sorted(self._tok_dirty):
            self.con.execute(
                "UPDATE reading SET tokens=? WHERE slug=?",
                (json.dumps(self._tok[slug], ensure_ascii=False), slug))

    def token_fix(self, slug: str, idx: int, surface: str,
                  old_r: str, old_ro: str, new_r: str, new_ro: str, why: str) -> None:
        """Repair one token's reading + romaji, matched on its exact current (s, r, ro)."""
        label = f"{slug}.tokens[{idx}] {surface}"
        toks = self.tokens(slug)
        if toks is None:
            self.skip(label, "no such reading, or tokens JSON is not byte-reproducible"); return
        if not 0 <= idx < len(toks):
            self.skip(label, f"index out of range (box has {len(toks)} tokens)"); return
        t = toks[idx]
        if t.get("s") != surface:
            self.skip(label, f"surface at this index is {t.get('s')!r}, not {surface!r} -- token stream moved")
            return
        if t.get("r") == new_r and t.get("ro") == new_ro:
            self.noop += 1; return
        if t.get("r") != old_r or t.get("ro") != old_ro:
            self.skip(label, f"current is r={t.get('r')!r}/ro={t.get('ro')!r}, expected the broken "
                             f"r={old_r!r}/ro={old_ro!r} or the repaired r={new_r!r}/ro={new_ro!r}")
            return
        self.hit(f"{label}: {old_r}/{old_ro} -> {new_r}/{new_ro}", why)
        if not self.check:
            t["r"] = new_r
            t["ro"] = new_ro
            self._tok_dirty.add(slug)

    # ---- reading.translation_pt ----
    def translation_pt(self, slug: str, before: str, after: str, why: str) -> None:
        label = f"{slug}.translation_pt"
        row = self.con.execute("SELECT translation_pt FROM reading WHERE slug=?", (slug,)).fetchone()
        if row is None:
            self.skip(label, "no such reading"); return
        cur = row[0]
        if cur == after:
            self.noop += 1; return
        if cur != before:
            self.skip(label, "current value is neither the expected quoted text nor the repair"); return
        self.hit(label, why)
        if not self.check:
            self.con.execute("UPDATE reading SET translation_pt=? WHERE slug=?", (after, slug))


