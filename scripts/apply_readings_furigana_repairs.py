def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="report what would change; write nothing")
    args = ap.parse_args()

    r = Repairs(args.check)
    for fn in (section_1, section_2, section_3, section_4, section_5):
        fn(r)

    if not args.check:
        r.tok_save_all()
        r.con.commit()

    verb = "would repair" if args.check else "repaired"
    print(f"\n{verb} {r.changed} token/field(s); {r.noop} already correct; {len(r.skipped)} skipped")
    for s in r.skipped:
        print(f"  ! {s}")
    return 1 if (args.check and r.changed) else 0


if __name__ == "__main__":
    sys.exit(main())
