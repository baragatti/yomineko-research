class Corpus:
    """Read-only view of the bank tables the boxes were assembled from."""

    def __init__(self, con: sqlite3.Connection) -> None:
        self.jp: dict[str, str] = {}
        self.sid: dict[str, int] = {}
        self.en: dict[str, str] = {}
        self.pt: dict[str, str] = {}
        self.tokens: dict[str, list[dict]] = {}
        self.kanji: dict[str, set[int]] = {}
        self.vocab: dict[str, set[int]] = {}
        loc_pt = {e: v for e, v in con.execute(
            "SELECT entity_id,value FROM localized_text WHERE entity_type='sentence' "
            "AND field='translation' AND locale='pt-BR'")}
        loc_en = {e: v for e, v in con.execute(
            "SELECT entity_id,value FROM localized_text WHERE entity_type='sentence' "
            "AND field='translation' AND locale='en'")}
        by_id: dict[int, str] = {}
        for sid, slug, jp, en in con.execute("SELECT id,slug,jp,en FROM sentence"):
            by_id[sid] = slug
            self.sid[slug] = sid
            self.jp[slug] = jp
            self.en[slug] = en or loc_en.get(sid) or ""
            self.pt[slug] = loc_pt.get(sid) or ""
            self.kanji[slug] = set()
            self.vocab[slug] = set()
        for sid, surf, rdg, romaji, pos in con.execute(
                "SELECT sentence_id,surface,reading,romaji,pos FROM token WHERE split_mode='C' "
                "ORDER BY sentence_id, id"):
            if sid not in by_id:
                continue
            ro = PUNCT_RO.get(surf, romaji) if (pos == "punctuation" and romaji == surf) else romaji
            self.tokens.setdefault(by_id[sid], []).append({"s": surf, "r": rdg, "ro": ro, "pos": pos})
        for sid, kid in con.execute("SELECT sentence_id,kanji_id FROM sentence_kanji"):
            if sid in by_id:
                self.kanji[by_id[sid]].add(kid)
        for sid, vid in con.execute("SELECT sentence_id,vocab_id FROM sentence_vocab"):
            if sid in by_id:
                self.vocab[by_id[sid]].add(vid)

    def text(self, slug: str, locale: str) -> str:
        return self.pt[slug] if locale == "pt" else self.en[slug]


class Box:
    """One reading row, held in memory so both repair passes compose before anything is written."""

    def __init__(self, slug: str, row: tuple) -> None:
        self.slug = slug
        self.jp: str = row[0]
        self.tokens: list[dict] = json.loads(row[1])
        self.pt: str = row[2]
        self.en: str = row[3]
        self.uses: dict = json.loads(row[4] or "{}")
        self.src: list[str] = json.loads(row[5])
        self.dirty = False


class Repairs:
    def __init__(self, check: bool) -> None:
        self.check = check
        self.con = sqlite3.connect(DB)
        self.con.execute("PRAGMA busy_timeout=60000")
        self.corpus = Corpus(self.con)
        self.boxes: dict[str, Box] = {}
        self.changed = 0
        self.noop = 0
        self.skipped: list[str] = []
        self._section = ""

    # ---- reporting ----
    def section(self, title: str) -> None:
        self._section = title
        print(f"\n== {title}")

    def hit(self, label: str, why: str) -> None:
        self.changed += 1
        print(f"  + {label}\n      why: {why}")

    def skip(self, label: str, reason: str) -> None:
        self.skipped.append(f"[{self._section}] {label}: {reason}")
        print(f"  ! SKIP {label}: {reason}")

    # ---- box access ----
    def box(self, slug: str) -> Box | None:
        if slug in self.boxes:
            return self.boxes[slug]
        row = self.con.execute(
            "SELECT jp,tokens,translation_pt,translation_en,uses,source_slugs FROM reading WHERE slug=?",
            (slug,)).fetchone()
        if row is None:
            return None
        b = Box(slug, row)
        self.boxes[slug] = b
        return b

    def segments(self, b: Box) -> list[dict] | None:
        """Split the box's jp + token stream back into its source sentences.

        Returns one entry per source slug with the character and token span it occupies and whether a
        boundary 。 has already been inserted after it. Returns None -- caller skips loudly -- if the
        box's jp or tokens are not exactly what its source sentences plus inserted boundaries produce.
        """
        out: list[dict] = []
        cpos = tpos = 0
        for i, slug in enumerate(b.src):
            jp = self.corpus.jp.get(slug)
            toks = self.corpus.tokens.get(slug)
            if jp is None or toks is None:
                return None
            n = len(toks)
            if b.jp[cpos:cpos + len(jp)] != jp:
                return None
            if "".join(t["s"] for t in b.tokens[tpos:tpos + n]) != jp:
                return None
            seg = {"slug": slug, "c0": cpos, "c1": cpos + len(jp), "t0": tpos, "t1": tpos + n, "dot": False}
            cpos += len(jp)
            tpos += n
            if (i < len(b.src) - 1 and jp[-1] not in TERMINAL
                    and b.jp[cpos:cpos + 1] == "。"
                    and tpos < len(b.tokens) and b.tokens[tpos]["s"] == "。"):
                seg["dot"] = True
                cpos += 1
                tpos += 1
            out.append(seg)
        if cpos != len(b.jp) or tpos != len(b.tokens):
            return None
        return out

    def joined(self, b: Box, locale: str, replace: tuple[int, str] | None = None) -> str:
        """The box's translation as its slots spell it, with the declared per-slot overrides applied."""
        parts = []
        for i, slug in enumerate(b.src):
            if replace and replace[0] == i:
                parts.append(self.corpus.text(replace[1], locale))
                continue
            ov = SLOT_OVERRIDE.get((b.slug, i, locale))
            parts.append(ov if ov is not None else self.corpus.text(slug, locale))
        return " ".join(parts).strip()

    def save(self) -> None:
        for slug, b in sorted(self.boxes.items()):
            if not b.dirty:
                continue
            self.con.execute(
                "UPDATE reading SET jp=?,tokens=?,translation_pt=?,translation_en=?,uses=?,source_slugs=? "
                "WHERE slug=?",
                (b.jp, json.dumps(b.tokens, ensure_ascii=False), b.pt, b.en,
                 json.dumps(b.uses, ensure_ascii=False), json.dumps(b.src, ensure_ascii=False), slug))


