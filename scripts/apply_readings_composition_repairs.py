def section_1(r: Repairs) -> None:
    r.section("1. A5 -- boxes that select two sentences saying the same thing")
    for box_slug, idx, old, new, why in DUPLICATES:
        label = f"{box_slug}[{idx}] {old} -> {new}"
        b = r.box(box_slug)
        if b is None:
            r.skip(label, "no such reading"); continue
        if not 0 <= idx < len(b.src):
            r.skip(label, f"slot out of range (box has {len(b.src)} sentences)"); continue
        if b.src[idx] == new:
            r.noop += 1; continue
        if b.src[idx] != old:
            r.skip(label, f"slot holds {b.src[idx]}, not the expected {old} -- selection moved"); continue
        if new in b.src:
            r.skip(label, f"{new} is already in this box"); continue
        segs = r.segments(b)
        if segs is None:
            r.skip(label, "jp/tokens are not what the source sentences produce -- box edited elsewhere")
            continue
        before_pt, before_en = r.joined(b, "pt"), r.joined(b, "en")
        if b.pt != before_pt:
            r.skip(label, "translation_pt is not what its slots spell (undeclared drift)"); continue
        if b.en != before_en:
            r.skip(label, "translation_en is not what its slots spell (undeclared drift)"); continue
        # `uses` must still be the build-time snapshot this repair does set arithmetic on
        others = [s for j, s in enumerate(b.src) if j != idx]
        drop_k = r.corpus.kanji[old] - {k for s in others for k in r.corpus.kanji[s]}
        drop_v = r.corpus.vocab[old] - {v for s in others for v in r.corpus.vocab[s]}
        new_k = sorted((set(b.uses.get("kanji", [])) - drop_k) | r.corpus.kanji[new])
        new_v = sorted((set(b.uses.get("vocab", [])) - drop_v) | r.corpus.vocab[new])

        seg = segs[idx]
        # splice jp: the outgoing sentence AND any boundary 。 that was inserted after it; section 2
        # re-adds one if the incoming sentence also needs it.
        c1 = seg["c1"] + (1 if seg["dot"] else 0)
        t1 = seg["t1"] + (1 if seg["dot"] else 0)
        b.jp = b.jp[:seg["c0"]] + r.corpus.jp[new] + b.jp[c1:]
        b.tokens = b.tokens[:seg["t0"]] + [dict(t) for t in r.corpus.tokens[new]] + b.tokens[t1:]
        b.pt = r.joined(b, "pt", replace=(idx, new))
        b.en = r.joined(b, "en", replace=(idx, new))
        b.uses = {"kanji": new_k, "vocab": new_v}
        b.src = list(b.src)
        b.src[idx] = new
        b.dirty = True
        r.hit(f"{label}\n      out: {r.corpus.jp[old]}  ({r.corpus.pt[old]})"
              f"\n      in : {r.corpus.jp[new]}  ({r.corpus.pt[new]})", why)


def section_2(r: Repairs) -> None:
    r.section("2. A4 -- sentence junctions glued together with no punctuation")
    for box_slug, idx, slug, kind, junction in RUNONS:
        label = f"{box_slug}[{idx}] {junction}"
        b = r.box(box_slug)
        if b is None:
            r.skip(label, "no such reading"); continue
        if not 0 <= idx < len(b.src) - 1:
            r.skip(label, f"slot {idx} is not an internal junction (box has {len(b.src)} sentences)")
            continue
        if b.src[idx] != slug:
            r.skip(label, f"slot holds {b.src[idx]}, not the expected {slug} -- selection moved"); continue
        if r.corpus.jp[slug][-1] in TERMINAL:
            r.skip(label, "this sentence already ends in a sentence-final mark of its own"); continue
        segs = r.segments(b)
        if segs is None:
            r.skip(label, "jp/tokens are not what the source sentences produce -- box edited elsewhere")
            continue
        seg = segs[idx]
        if seg["dot"]:
            r.noop += 1; continue
        b.jp = b.jp[:seg["c1"]] + "。" + b.jp[seg["c1"]:]
        b.tokens = b.tokens[:seg["t1"]] + [dict(DOT_TOKEN)] + b.tokens[seg["t1"]:]
        b.dirty = True
        extra = RUNON_MISPARSE.get((box_slug, idx))
        r.hit(label, RUNON_WHY[kind] + (f" {extra}" if extra else ""))


