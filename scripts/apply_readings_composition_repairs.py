def main() -> int:
    ap = argparse.ArgumentParser(description="Reading-box composition repairs (QA sweep A4 + A5).")
    ap.add_argument("--check", action="store_true", help="report what would change; write nothing")
    args = ap.parse_args()

    r = Repairs(args.check)
    section_1(r)
    section_2(r)

    if not args.check:
        r.save()
        r.con.commit()

    verb = "would repair" if args.check else "repaired"
    print(f"\n{verb} {r.changed} junction/selection(s) across {sum(1 for b in r.boxes.values() if b.dirty)} "
          f"boxes; {r.noop} already correct; {len(r.skipped)} skipped")
    for s in r.skipped:
        print(f"  ! {s}")
    return 1 if (args.check and r.changed) else 0


