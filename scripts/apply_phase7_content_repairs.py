def _practice_block(prefix: str, n: int, lead: str, tail: str) -> str:
    refs = "\n".join(f'<exercise ref="{prefix}-{i}"/>' for i in range(1, n + 1))
    return f'{lead}<heading level="3"><text>Hora de praticar</text></heading>\n{refs}{tail}'


