#!/usr/bin/env python3
"""Phase-7 content repairs: confirmed learner-facing corruption across corpus + courseware.

Two independent audits (digests `wtg6uvktk` and `wlv7ltx8b`) found content defects that survive in the
live data: QA-reviewer instructions pasted into learner-facing fields, truncated sentences, empty
furigana, exercises that grade their own revealed answer as wrong, authored exercises the lesson body
never references, and accent-stripped pt-BR. Each defect below carries its own `why`.

STORAGE MODEL. A lesson lives in TWO synchronised layers:
  * the tracked authoring source `research/derived/lessons/<slug>.json` (what load_lessons.py re-authors
    the DB from -- the durable layer), and
  * `db/corpus.sqlite` (`lesson`, `exercise`, `localized_text`) -- what the exporters read.
Every lesson-scoped repair here is applied to BOTH. Repairing only the DB is the exact mistake recorded
in `qa-repairs-absent-from-authoring-source`: the next `load_lessons.py` run wipes it.
Corpus-side repairs (sentence bank, readings, grammar, kanji links) exist only in the DB; the JSON under
`corpus/` and `course/` is regenerated by the exporters afterwards and is NEVER edited here.

Every edit is matched on its EXACT current value. If the current value is neither the expected corrupted
text nor the repaired text, the edit is SKIPPED loudly and nothing is written. Re-running reports 0.

Usage: apply_phase7_content_repairs.py [--check]
Run the exporters afterwards (export_course.py / export_corpus.py / export_readings.py); do NOT run
load_lessons.py before the exporters, and never before this script's source-layer writes are committed.
"""
from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "db" / "corpus.sqlite"
LESSON_SRC = ROOT / "research" / "derived" / "lessons"

# The corpus mixes the two Japanese tilde characters. Spelling them as escapes keeps each repair on the
# same character its own record already uses, so a fixed pattern still matches its siblings.
WAVE = "〜"    # 〜 WAVE DASH        -- used inside gram:gp-83
FWTIL = "～"   # ～ FULLWIDTH TILDE  -- used by every gram:n3-* record


# --------------------------------------------------------------------------------------------------
# plumbing
# --------------------------------------------------------------------------------------------------
class Repairs:
    def __init__(self, check: bool) -> None:
        self.check = check
        self.con = sqlite3.connect(DB)
        self.con.execute("PRAGMA busy_timeout=60000")
        self.changed = 0
        self.noop = 0
        self.skipped: list[str] = []
        self._src: dict[str, tuple[dict, str, bool]] = {}   # slug -> (obj, newline, trailing_nl)
        self._src_dirty: set[str] = set()
        self._section = ""

    # ---- reporting ----
    def section(self, title: str) -> None:
        self._section = title
        print(f"\n== {title}")

    def hit(self, label: str, why: str) -> None:
        self.changed += 1
        print(f"  + {label}\n      why: {why}")

    def skip(self, label: str, reason: str) -> None:
        self.skipped.append(f"[{self._section}] {label}: {reason}")
        print(f"  ! SKIP {label}: {reason}")

    # ---- id lookups ----
    def lesson_id(self, slug: str):
        r = self.con.execute("SELECT id FROM lesson WHERE slug=?", (slug,)).fetchone()
        return r[0] if r else None

    def exercise_row(self, slug: str):
        return self.con.execute(
            "SELECT e.id, e.lesson_id, e.answer, l.slug FROM exercise e JOIN lesson l ON l.id=e.lesson_id "
            "WHERE e.slug=?", (slug,)).fetchone()

    def sentence_id(self, slug: str):
        r = self.con.execute("SELECT id FROM sentence WHERE slug=?", (slug,)).fetchone()
        return r[0] if r else None

    def token_id(self, sent_slug: str, idx: int):
        """bank.json tokens[] order == ORDER BY split_mode, position (see export_corpus.py)."""
        sid = self.sentence_id(sent_slug)
        if sid is None:
            return None
        rows = self.con.execute(
            "SELECT id FROM token WHERE sentence_id=? ORDER BY split_mode, position", (sid,)).fetchall()
        return rows[idx][0] if 0 <= idx < len(rows) else None

    def particle_id(self, sent_slug: str, idx: int):
        """bank.json particles[] order == the exporter's unordered SELECT, i.e. rowid order."""
        sid = self.sentence_id(sent_slug)
        if sid is None:
            return None
        rows = self.con.execute("SELECT id FROM particle WHERE sentence_id=?", (sid,)).fetchall()
        return rows[idx][0] if 0 <= idx < len(rows) else None

    def grammar_id(self, slug: str):
        r = self.con.execute("SELECT id FROM grammar_point WHERE slug=?", (slug,)).fetchone()
        return r[0] if r else None

    # ---- localized_text ----
    def lt_get(self, etype: str, eid: int, field: str, locale: str = "pt-BR"):
        r = self.con.execute(
            "SELECT value, is_list FROM localized_text WHERE entity_type=? AND entity_id=? AND field=? "
            "AND locale=?", (etype, eid, field, locale)).fetchone()
        return r if r else (None, None)

    def lt_put(self, etype: str, eid: int, field: str, locale: str, value: str) -> None:
        self.con.execute(
            "UPDATE localized_text SET value=? WHERE entity_type=? AND entity_id=? AND field=? AND locale=?",
            (value, etype, eid, field, locale))

    def lt_set(self, label: str, why: str, etype: str, eid, field: str, locale: str,
               before: str, after: str) -> bool:
        """Whole-value replacement of one localized_text row, matched on its exact current value."""
        if eid is None:
            self.skip(label, "entity not found"); return False
        raw, _ = self.lt_get(etype, eid, field, locale)
        if raw is None:
            self.skip(label, "no localized_text row"); return False
        if raw == after:
            self.noop += 1; return False
        if raw != before:
            self.skip(label, "current value is neither the expected corrupted text nor the repair"); return False
        self.hit(label, why)
        if not self.check:
            self.lt_put(etype, eid, field, locale, after)
        return True

    def lt_sub(self, label: str, why: str, etype: str, eid, field: str, locale: str,
               before: str, after: str, guard: str | None = None) -> bool:
        """Substring replacement inside one localized_text row (bodies, long prose).

        `guard` is a string that exists ONLY once the repair has been applied. It is required whenever
        `after` still contains `before` (an insertion), because the plain not-in/in test cannot tell
        'not yet applied' from 'applied' in that case, and re-running would insert a second copy.
        """
        if eid is None:
            self.skip(label, "entity not found"); return False
        raw, _ = self.lt_get(etype, eid, field, locale)
        if raw is None:
            self.skip(label, "no localized_text row"); return False
        if guard is not None and guard in raw:
            self.noop += 1; return False
        if before not in raw:
            if after in raw:
                self.noop += 1
            else:
                self.skip(label, "expected substring not found")
            return False
        if raw.count(before) != 1:
            self.skip(label, f"expected substring occurs {raw.count(before)}x, need exactly 1"); return False
        self.hit(label, why)
        if not self.check:
            self.lt_put(etype, eid, field, locale, raw.replace(before, after))
        return True

    def lt_delete(self, label: str, why: str, etype: str, eid, field: str, locale: str, before: str) -> bool:
        if eid is None:
            self.skip(label, "entity not found"); return False
        raw, _ = self.lt_get(etype, eid, field, locale)
        if raw is None:
            self.noop += 1; return False           # already removed
        if raw != before:
            self.skip(label, "current value is not the expected text"); return False
        self.hit(label, why)
        if not self.check:
            self.con.execute(
                "DELETE FROM localized_text WHERE entity_type=? AND entity_id=? AND field=? AND locale=?",
                (etype, eid, field, locale))
        return True

    # ---- authoring source (research/derived/lessons/<slug>.json) ----
    def src_load(self, lesson_slug: str):
        if lesson_slug in self._src:
            return self._src[lesson_slug]
        p = LESSON_SRC / (lesson_slug.replace("les:", "") + ".json")
        if not p.exists():
            return None
        raw = p.read_text(encoding="utf-8", newline="")
        newline = "\r\n" if "\r\n" in raw else "\n"
        norm = raw.replace("\r\n", "\n")
        trailing = norm.endswith("\n")
        obj = json.loads(norm)
        # Fidelity gate: only edit the object when re-serialising it reproduces the file byte for byte,
        # so an unrelated whitespace reflow can never ride along with a content repair.
        if json.dumps(obj, ensure_ascii=False, indent=2) + ("\n" if trailing else "") != norm:
            return None
        self._src[lesson_slug] = (obj, newline, trailing)
        return self._src[lesson_slug]

    def src_save_all(self) -> None:
        for slug in sorted(self._src_dirty):
            obj, newline, trailing = self._src[slug]
            p = LESSON_SRC / (slug.replace("les:", "") + ".json")
            text = json.dumps(obj, ensure_ascii=False, indent=2) + ("\n" if trailing else "")
            p.write_bytes(text.replace("\n", newline).encode("utf-8"))

    @staticmethod
    def _node(obj: dict, path: tuple):
        """Resolve a source path to (container, key). Exercise steps address by slug."""
        cur = obj
        for i, step in enumerate(path[:-1]):
            if step == "exercises":
                slug = path[i + 1]
                match = [e for e in cur["exercises"] if e.get("slug") == slug]
                if not match:
                    return None
                cur = match[0]
                if i + 2 >= len(path):
                    return None
                return Repairs._node(cur, path[i + 2:])
            cur = cur[step]
        key = path[-1]
        if isinstance(cur, list) and not isinstance(key, int):
            return None
        return cur, key

    def src_edit(self, label: str, lesson_slug: str, path: tuple, before, after, mode: str = "set",
                 guard: str | None = None) -> str:
        """mode: 'set' (exact whole value) or 'sub' (substring inside a string value)."""
        loaded = self.src_load(lesson_slug)
        if loaded is None:
            return "skip:source file missing or not byte-reproducible"
        obj, _, _ = loaded
        node = self._node(obj, path)
        if node is None:
            return "skip:source path not found"
        cur, key = node
        try:
            val = cur[key]
        except (KeyError, IndexError, TypeError):
            return "skip:source path not found"
        if guard is not None and isinstance(val, str) and guard in val:
            return "noop"
        if mode == "set":
            if val == after:
                return "noop"
            if val != before:
                return "skip:source value is neither the expected corrupted text nor the repair"
            new = after
        else:
            if before not in val:
                return "noop" if after in val else "skip:expected substring not in source"
            if val.count(before) != 1:
                return f"skip:expected substring occurs {val.count(before)}x in source"
            new = val.replace(before, after)
        if not self.check:
            cur[key] = new
            self._src_dirty.add(lesson_slug)
        return "applied"

    # ---- combined helpers: patch BOTH layers ----
    def lesson_field(self, lesson_slug: str, field: str, idx, before: str, after: str, why: str) -> None:
        """title / description / objectives[i] -- DB localized_text + authoring source."""
        label = f"{lesson_slug}.{field}" + ("" if idx is None else f"[{idx}]")
        lid = self.lesson_id(lesson_slug)
        if lid is None:
            self.skip(label, "no such lesson"); return
        raw, is_list = self.lt_get("lesson", lid, field)
        if raw is None:
            self.skip(label + " (db)", "no localized_text row")
        else:
            cur = json.loads(raw)[idx] if is_list else raw
            if cur == after:
                self.noop += 1
            elif cur != before:
                self.skip(label + " (db)", "current value is neither the expected corrupted text nor the repair")
            else:
                self.hit(label + " (db)", why)
                if not self.check:
                    if is_list:
                        items = json.loads(raw); items[idx] = after
                        self.lt_put("lesson", lid, field, "pt-BR", json.dumps(items, ensure_ascii=False))
                    else:
                        self.lt_put("lesson", lid, field, "pt-BR", after)
        path = (field,) if idx is None else (field, idx)
        st = self.src_edit(label, lesson_slug, path, before, after)
        self._report_src(label, st, why)

    def lesson_body(self, lesson_slug: str, before: str, after: str, why: str, tag: str = "",
                    guard: str | None = None) -> None:
        label = f"{lesson_slug}.body{tag}"
        lid = self.lesson_id(lesson_slug)
        if lid is None:
            self.skip(label, "no such lesson"); return
        self.lt_sub(label + " (db)", why, "lesson", lid, "body", "pt-BR", before, after, guard=guard)
        st = self.src_edit(label, lesson_slug, ("body",), before, after, mode="sub", guard=guard)
        self._report_src(label, st, why)

    def exercise_text(self, ex_slug: str, field: str, before: str, after: str, why: str,
                      mode: str = "set") -> None:
        """prompt / explanation -- DB localized_text + authoring source."""
        label = f"{ex_slug}.{field}"
        row = self.exercise_row(ex_slug)
        if row is None:
            self.skip(label, "no such exercise"); return
        eid, _lid, _ans, lesson_slug = row
        if mode == "set":
            self.lt_set(label + " (db)", why, "exercise", eid, field, "pt-BR", before, after)
        else:
            self.lt_sub(label + " (db)", why, "exercise", eid, field, "pt-BR", before, after)
        st = self.src_edit(label, lesson_slug, ("exercises", ex_slug, field), before, after, mode=mode)
        self._report_src(label, st, why)

    def exercise_answer(self, ex_slug: str, before: dict, after: dict, why: str) -> None:
        """The structured answer key -- DB exercise.answer column + authoring source."""
        label = f"{ex_slug}.answer"
        row = self.exercise_row(ex_slug)
        if row is None:
            self.skip(label, "no such exercise"); return
        eid, _lid, raw, lesson_slug = row
        cur = json.loads(raw) if raw else None
        if cur == after:
            self.noop += 1
        elif cur != before:
            self.skip(label + " (db)", "current answer is neither the expected value nor the repair")
        else:
            self.hit(label + " (db)", why)
            if not self.check:
                self.con.execute("UPDATE exercise SET answer=? WHERE id=?",
                                 (json.dumps(after, ensure_ascii=False), eid))
        st = self.src_edit(label, lesson_slug, ("exercises", ex_slug, "answer"), before, after)
        self._report_src(label, st, why)

    def _report_src(self, label: str, status: str, why: str) -> None:
        if status == "applied":
            self.hit(label + " (source)", why)
        elif status == "noop":
            self.noop += 1
        else:
            self.skip(label + " (source)", status.split(":", 1)[1])


