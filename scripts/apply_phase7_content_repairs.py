def _gram_col(r: Repairs, slug: str, col: str, before, after, label: str, why: str) -> None:
    gid = r.grammar_id(slug)
    if gid is None:
        r.skip(label, "no such grammar point"); return
    cur = r.con.execute(f"SELECT {col} FROM grammar_point WHERE id=?", (gid,)).fetchone()[0]
    if cur == after:
        r.noop += 1; return
    if cur != before:
        r.skip(label, "current value is neither the expected corrupted text nor the repair"); return
    r.hit(label, why)
    if not r.check:
        r.con.execute(f"UPDATE grammar_point SET {col}=? WHERE id=?", (after, gid))


