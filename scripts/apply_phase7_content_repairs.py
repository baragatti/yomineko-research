def section_10(r: Repairs) -> None:
    r.section("10. vocab_sense 'maca' -> 'maçã'")
    rows = r.con.execute(
        "SELECT lt.entity_id, lt.value, v.headword FROM localized_text lt "
        "JOIN vocab_sense vs ON vs.id = lt.entity_id JOIN vocab v ON v.id = vs.vocab_id "
        "WHERE lt.entity_type='vocab_sense' AND lt.locale='pt-BR' AND lt.value LIKE '%\"maca\"%'"
    ).fetchall()
    if not rows:
        r.skip("vocab_sense maca", "no gloss contains the bare word 'maca'")
        return
    for eid, value, headword in rows:
        # Guard: only an apple word may become 'maçã'.
        if headword in ("林檎", "りんご", "リンゴ"):
            r.lt_set(f"vocab_sense[{eid}].gloss.pt-BR",
                     "Accent-stripped 'maca' for 'maçã' (apple).",
                     "vocab_sense", eid, "gloss", "pt-BR", value,
                     value.replace('"maca"', '"maçã"'))
        else:
            r.skip(
                f"vocab_sense[{eid}].gloss.pt-BR (vocab {headword})",
                f"REFUSED: value is {value!r} on headword {headword} (たんか, a medical stretcher). "
                "'maca' is the correct pt-BR word for a stretcher; 'maçã' (apple) would be a "
                "mistranslation. The audit's nasal-lexicon detector produced a false positive here.",
            )


